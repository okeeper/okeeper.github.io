// Run only from the production publishing workflow. Ordinary local builds remain offline.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';

const command = process.argv[2];
const revision = process.env.GITHUB_SHA;
if (!/^[0-9a-f]{40}$/.test(revision || '')) throw new Error('Expected a Git commit SHA in GITHUB_SHA.');
const host = readFileSync('CNAME', 'utf8').trim();
const origin = 'https://' + host;
const manifestName = 'indexnow-state.json';
const keyFile = '/indexnow-key.txt';

function canonicalUrl(value) {
  const url = new URL(value);
  if (url.origin !== origin || url.username || url.password || url.search || url.hash) {
    throw new Error('Unexpected URL in the search notification manifest.');
  }
  return url;
}

async function getState(afterDeployment) {
  for (let attempt = 0; attempt < 5; attempt++) {
    try {
      const response = await fetch(origin + '/' + manifestName + '?release=' + revision + '&check=' + Date.now(), {
        signal: AbortSignal.timeout(12000),
      });
      if (response.status === 404 && !afterDeployment) return null;
      if (!response.ok) throw new Error('Manifest HTTP ' + response.status);
      const state = await response.json();
      if (!state.pages || Array.isArray(state.pages) || typeof state.pages !== 'object' ||
          !Array.isArray(state.changed)) throw new Error('Invalid IndexNow manifest');
      if (afterDeployment && state.revision !== revision) throw new Error('Waiting for the new Pages revision');
      return state;
    } catch (error) {
      if (attempt === 4) throw error;
      await delay(3000);
    }
  }
}

async function prepare() {
  const previous = await getState(false);
  const pages = Object.create(null);
  // This XML is generated by writeFeeds, which emits one UTF-8, absolute <loc> per canonical page.
  const sitemap = readFileSync('dist/sitemap.xml', 'utf8');
  const escapes = {amp:'&',lt:'<',gt:'>',apos:"'",quot:'"'};
  for (const [, loc] of sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)) {
    const url = canonicalUrl(loc.replace(/&(amp|lt|gt|apos|quot);/g, (_, entity) => escapes[entity]));
    const file = join('dist', decodeURIComponent(url.pathname), url.pathname.endsWith('/') ? 'index.html' : '');
    pages[url.href] = createHash('sha256').update(readFileSync(file)).digest('hex');
  }
  if (!Object.hasOwn(pages, origin + '/')) throw new Error('Missing canonical homepage');
  const prior = previous?.pages || {};
  const urls = new Set([...Object.keys(pages), ...Object.keys(prior)]);
  const changed = [...urls].filter(url => pages[url] !== prior[url]);
  // A full re-run for the same deployed revision can retry its original batch.
  if (previous?.revision === revision) changed.push(...previous.changed);
  const state = {revision, pages, changed:[...new Set(changed)]};
  writeFileSync('dist/' + manifestName, JSON.stringify(state));
  console.log('Prepared ' + state.changed.length + ' changed canonical URLs for ' + revision + '.');
}

async function submit() {
  const state = await getState(true);
  const urls = state.changed.map(value => canonicalUrl(value).href);
  if (!urls.length) return console.log('No canonical page changes to submit.');
  const key = readFileSync('public' + keyFile, 'utf8').trim();
  if (!/^[a-zA-Z0-9-]{8,128}$/.test(key)) throw new Error('Invalid public IndexNow key');
  const keyLocation = origin + keyFile;
  const live = await fetch(keyLocation, {signal: AbortSignal.timeout(12000)});
  if (!live.ok || (await live.text()).trim() !== key) throw new Error('Published ownership key does not match.');
  for (let offset = 0; offset < urls.length; offset += 10000) {
    const urlList = urls.slice(offset, offset + 10000);
    const response = await fetch('https://api.indexnow.org/indexnow', {
      method: 'POST', headers: {'Content-Type':'application/json; charset=utf-8'},
      body: JSON.stringify({host, key, keyLocation, urlList}), signal: AbortSignal.timeout(30000),
    });
    if (![200,202].includes(response.status)) throw new Error('IndexNow returned HTTP ' + response.status);
    console.log('IndexNow received ' + urlList.length + ' URLs (HTTP ' + response.status + ').');
  }
}

if (command === 'prepare') await prepare();
else if (command === 'submit') await submit();
else throw new Error('Usage: node scripts/indexnow.mjs prepare|submit');
